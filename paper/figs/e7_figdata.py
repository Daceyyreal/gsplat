"""Shared reading and writing for E7's paper tables and figures (``paper/figs/e7_*.py``).

Every number comes from ``bench/gn/e7.py`` by import: ``e7.verdict(root)`` (the primaries, both test families with
Holm's order, the outcomes, the fragile flag and the secondaries of Amendment 20 f-h) and ``e7.load`` /
``e7.scene_data`` for the arm curves. Nothing here recomputes a BD, a noise piece or a test.

``root`` is a directory of E7 bundles, each ``<root>/<bundle>/gn7/`` (the committed layout is
``kaggle/gn_e7/S#/gn7/``). ``out`` is where the outputs go. Writing into ``paper/figs/out/`` is allowed only from the
committed bundles (``kaggle/gn_e7``), so stand-in data can never overwrite a paper output.
"""

import csv
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
for _p in (HERE, os.path.join(REPO, "bench", "gn"), os.path.join(REPO, "kaggle")):
    if _p not in sys.path:
        sys.path.insert(0, _p)
import figdata as fd  # noqa: E402  (tex escaping, the matplotlib set-up, byte-stable saving)

E7_ROOT = os.path.join(REPO, "kaggle", "gn_e7")
PAPER_OUT = fd.OUT
ARMS = ("R", "G", "CG", "K", "O")
METHODS = ("c3dgs", "ogc_gram")
PRIMARY_LABEL = {"refit": r"$\Delta_{\mathrm{refit}}$ (BD$_G$ - BD$_R$)", "cb": r"$\Delta_{\mathrm{cb}}$ (BD$_{CG}$ - BD$_G$)"}
# arms: Okabe-Ito colour and marker each; methods: line style
ARM_STYLE = {"R": dict(color="#000000", marker="o"), "G": dict(color="#E69F00", marker="s"),
             "CG": dict(color="#56B4E9", marker="^"), "K": dict(color="#009E73", marker="v"),
             "O": dict(color="#CC79A7", marker="D")}
METHOD_LS = {"c3dgs": "-", "ogc_gram": "--"}


def check_out(root, out):
    """Refuse to write stand-in outputs into the paper's output directory."""
    if os.path.realpath(out) == os.path.realpath(PAPER_OUT) and os.path.realpath(root) != os.path.realpath(E7_ROOT):
        raise SystemExit(f"refused: outputs from {root} would go into {PAPER_OUT}; only {E7_ROOT} may write there")
    os.makedirs(out, exist_ok=True)


_CACHE = {}


def verdict(root):
    """``e7.verdict(root)``, once per root."""
    import e7

    key = os.path.realpath(root)
    if key not in _CACHE:
        _CACHE[key] = e7.verdict(root)
    return _CACHE[key]


def scene_curves(root, scene):
    """The scene's ``e7.scene_data`` (psnr and bytes keyed by (j, seed, row)) from the merged bundles."""
    import e7

    data = e7.load(root)
    return e7.scene_data(data["rows"].get(scene, []), scene)


def num(x, digits=6, sign=False):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "--"
    return f"{x:+.{digits}f}" if sign else f"{x:.{digits}f}"


def write_csv(out, name, header, rows):
    with open(os.path.join(out, name), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow(["" if x is None else repr(x) if isinstance(x, float) else x for x in r])


def write_tex(out, name, script, source, colspec, header, body, footer=()):
    lines = [f"% {source}", f"% generated by paper/figs/{script}.py from E7's bundles (bench/gn/e7.py); do not edit",
             f"\\begin{{tabular}}{{{colspec}}}", r"\toprule", " & ".join(fd.tex_escape(c) for c in header) + r" \\",
             r"\midrule"]
    lines += [" & ".join(fd.tex_escape(c) for c in r) + r" \\" for r in body]
    if footer:
        lines.append(r"\midrule")
        lines += [" & ".join(fd.tex_escape(c) for c in r) + r" \\" for r in footer]
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    with open(os.path.join(out, name), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines))


def save(fig, out, stem):
    fig.savefig(os.path.join(out, stem + ".pdf"), bbox_inches="tight",
                metadata={"CreationDate": None, "ModDate": None, "Producer": None, "Creator": None})
    fig.savefig(os.path.join(out, stem + ".png"), bbox_inches="tight", metadata={"Software": None})


def cli(main, doc):
    import argparse

    ap = argparse.ArgumentParser(description=doc.split("\n\n")[0])
    ap.add_argument("--root", default=E7_ROOT, help="a directory of E7 bundles, <root>/<bundle>/gn7/")
    ap.add_argument("--out", default=PAPER_OUT, help="the output directory")
    a = ap.parse_args()
    check_out(a.root, a.out)
    main(a.root, a.out)
